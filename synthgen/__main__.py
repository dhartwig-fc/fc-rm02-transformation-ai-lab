"""Generate a synthetic AML dataset.

    python3 -m synthgen --seed 42 --customers 200 --days 90 --out data/synthetic/run-42

Writes customers.csv, accounts.csv, transactions.csv, alerts.csv,
ground_truth.csv (the answer key), rules.csv and manifest.json.
"""
import argparse
import csv
import json
import os
import sys
from collections import Counter
from pathlib import Path

from .core import GENERATOR_VERSION, Bank
from .rules import RULE_DESCRIPTION, RULE_TYPOLOGY, run_rules

RESTRICTED = ("data/real", "data/restricted", "cases")
BANNER = ("SYNTHETIC DATA - generated by synthgen. Every person, account and transaction is "
          "invented. IBANs use the non-existent bank code TEST.")


def _fmt(v):
    if hasattr(v, "isoformat"):
        return v.isoformat()
    if isinstance(v, list):
        return ";".join(v)
    return v


def write_csv(path, rows, fields):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow({k: _fmt(r[k]) for k in fields})


def check_out_dir(out):
    rel = os.path.relpath(Path(out).resolve(), Path.cwd()).replace(os.sep, "/")
    if any(rel == r or rel.startswith(r + "/") for r in RESTRICTED):
        raise SystemExit(f"refusing to write synthetic data into restricted location {rel!r}")


def generate(seed, customers, days, out, typology_rate=0.10, noise_rate=0.05):
    check_out_dir(out)
    bank = Bank(seed, customers, days, typology_rate, noise_rate).build()
    alerts = run_rules(bank)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)

    write_csv(out / "customers.csv", bank.customers,
              ["customer_id", "name", "date_of_birth", "nationality", "occupation", "risk_rating", "onboarded"])
    write_csv(out / "accounts.csv", bank.accounts, ["account_id", "customer_id", "iban", "product", "opened"])
    write_csv(out / "transactions.csv", bank.transactions,
              ["txn_id", "account_id", "timestamp", "direction", "amount", "currency", "channel",
               "counterparty_name", "counterparty_iban", "counterparty_country", "reference"])
    write_csv(out / "alerts.csv", alerts,
              ["alert_id", "rule_id", "customer_id", "account_id", "created_at", "txn_count",
               "total_amount", "txn_ids", "label"])
    write_csv(out / "ground_truth.csv", bank.cases, ["case_id", "customer_id", "typology", "txn_ids"])
    write_csv(out / "rules.csv",
              [{"rule_id": r, "typology": RULE_TYPOLOGY[r], "description": RULE_DESCRIPTION[r]}
               for r in RULE_TYPOLOGY], ["rule_id", "typology", "description"])

    labels = Counter(a["label"] for a in alerts)
    manifest = {
        "synthetic": True, "notice": BANNER, "generator_version": GENERATOR_VERSION,
        "seed": seed, "customers": customers, "days": days,
        "typology_rate": typology_rate, "noise_rate": noise_rate,
        "counts": {"customers": len(bank.customers), "accounts": len(bank.accounts),
                   "transactions": len(bank.transactions), "alerts": len(alerts),
                   "true_positive_alerts": labels["TRUE_POSITIVE"],
                   "false_positive_alerts": labels["FALSE_POSITIVE"],
                   "ground_truth_cases": len(bank.cases)},
        "cases_by_typology": dict(sorted(Counter(c["typology"] for c in bank.cases).items())),
        "warning": "alerts.csv 'label' and ground_truth.csv are the ANSWER KEY. Hide them from "
                   "any model you are evaluating.",
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def main(argv=None):
    p = argparse.ArgumentParser(prog="synthgen", description=__doc__.splitlines()[1].strip())
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--customers", type=int, default=200)
    p.add_argument("--days", type=int, default=90)
    p.add_argument("--typology-rate", type=float, default=0.10)
    p.add_argument("--noise-rate", type=float, default=0.05)
    p.add_argument("--out", default="data/synthetic/latest")
    a = p.parse_args(argv)
    m = generate(a.seed, a.customers, a.days, a.out, a.typology_rate, a.noise_rate)
    c = m["counts"]
    print(f"{BANNER}\nWrote {a.out}: {c['customers']} customers, {c['transactions']} transactions, "
          f"{c['alerts']} alerts ({c['true_positive_alerts']} true / {c['false_positive_alerts']} false "
          f"positives), {c['ground_truth_cases']} hidden cases {m['cases_by_typology']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
